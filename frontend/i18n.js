function getLang() {
    try {
        return localStorage.getItem("lang") === "hi" ? "hi" : "en";
    } catch (error) {
        return "en";
    }
}

function t(key, vars = {}) {
    const lang = getLang();
    const text = (I18N[lang] && I18N[lang][key]) ?? I18N.en[key] ?? key;
    return String(text).replace(/\{(\w+)\}/g, (match, name) =>
        vars[name] !== undefined && vars[name] !== null ? String(vars[name]) : match
    );
}

// Pick the Hindi or English version of a scheme field (title, tagline).
function localized(item, field) {
    if (!item) return "";
    if (getLang() === "hi" && item[`${field}_hi`]) return item[`${field}_hi`];
    if (field === "tagline" && !item.tagline && item.scheme_details) return item.scheme_details.tagline || "";
    return item[field] || "";
}

function applyTranslations(root = document) {
    root.querySelectorAll("[data-i18n]").forEach((el) => {
        el.textContent = t(el.dataset.i18n);
    });
    root.querySelectorAll("[data-i18n-html]").forEach((el) => {
        el.innerHTML = t(el.dataset.i18nHtml);
    });
    root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
        el.placeholder = t(el.dataset.i18nPlaceholder);
    });
    root.querySelectorAll("[data-i18n-title]").forEach((el) => {
        const text = t(el.dataset.i18nTitle);
        el.title = text;
        el.setAttribute("aria-label", text);
    });

    if (root === document) {
        document.documentElement.lang = getLang();
        const titleKey = document.body && document.body.dataset.titleKey;
        if (titleKey) document.title = t(titleKey);
        document.querySelectorAll(".lang-switch").forEach((button) => {
            // Full name on wide screens, a short label on phones (see style.css).
            button.innerHTML = `<span class="lang-long">${t("lang.switch")}</span><span class="lang-short">${t("lang.short")}</span>`;
            button.title = t("lang.switch_title");
            button.setAttribute("aria-label", t("lang.switch_title"));
        });
    }
}

function setLang(lang) {
    try {
        localStorage.setItem("lang", lang === "hi" ? "hi" : "en");
    } catch (error) {
        /* storage unavailable */
    }
    applyTranslations();
    document.dispatchEvent(new CustomEvent("languagechange", { detail: { lang: getLang() } }));
}

document.addEventListener("DOMContentLoaded", () => {
    applyTranslations();
    document.querySelectorAll(".lang-switch").forEach((button) => {
        button.addEventListener("click", () => setLang(getLang() === "hi" ? "en" : "hi"));
    });
});
